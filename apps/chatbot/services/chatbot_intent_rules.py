MATCH_FLOW_SUFFIXES = COMMON_SUFFIXES + (
    " 다음 단계",
    " 다음엔 뭐해",
    " 이후에는",
    " 왜 필요한데",
    " 어떤 기준",
    " 기준 알려줘",
    " 차이 알려줘",
    " 더 설명해줘",
)


def _expand_patterns(*phrases: str, suffixes: tuple[str, ...] = COMMON_SUFFIXES):
    patterns: list[str] = []
    for phrase in phrases:
        for suffix in suffixes:
            patterns.append(f"{phrase}{suffix}".strip())
    return tuple(dict.fromkeys(patterns))


